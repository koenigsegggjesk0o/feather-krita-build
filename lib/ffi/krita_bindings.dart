/// High-level Dart wrapper around the Krita C++ brush engine.
///
/// Owns a native brush handle and exposes a small set of methods used by the
/// Feather-Krita engine layer. The class is not re-entrant — callers must
/// ensure that brush operations are serialized.
///
/// Typical usage:
/// ```dart
/// final engine = KritaBrushEngine();
/// await engine.loadPreset('/path/to/brush.kpp');
/// engine.size = 32;
/// engine.color = const BrushColor(0, 0, 0);
/// final dab = engine.generateDab(BrushInput(x: 10, y: 20, pressure: 0.8));
/// engine.dispose();
/// ```
class KritaBrushEngine {
  KritaBrushEngine._(this._lib, this._handle);

  static DynamicLibrary? _cachedLib;

  /// Constructs a new engine instance, loading the native library and
  /// allocating a fresh brush handle.
  factory KritaBrushEngine() {
    final lib = _cachedLib ??= _loadKritaBridge();
    final init = lib.lookupFunction<_KritaBrushInitNative, _KritaBrushInitDart>(
        'krita_brush_init');
    final handle = init();
    if (handle == nullptr) {
      throw StateError('krita_brush_init returned a null handle');
    }
    return KritaBrushEngine._(lib, handle);
  }

  final DynamicLibrary _lib;
  final Pointer<Void> _handle;
  bool _disposed = false;

  // Cached lookups (lazy — they only resolve on first use).
  late final _KritaBrushDestroyDart _destroy =
      _lib.lookupFunction<_KritaBrushDestroyNative, _KritaBrushDestroyDart>(
          'krita_brush_destroy');
  late final _KritaBrushLoadPresetDart _loadPreset = _lib
      .lookupFunction<_KritaBrushLoadPresetNative, _KritaBrushLoadPresetDart>(
          'krita_brush_load_preset');
  late final _KritaBrushSetSizeDart _setSize = _lib
      .lookupFunction<_KritaBrushSetSizeNative, _KritaBrushSetSizeDart>(
          'krita_brush_set_size');
  late final _KritaBrushSetColorDart _setColor = _lib
      .lookupFunction<_KritaBrushSetColorNative, _KritaBrushSetColorDart>(
          'krita_brush_set_color');
  late final _KritaBrushSetOpacityDart _setOpacity = _lib
      .lookupFunction<_KritaBrushSetOpacityNative, _KritaBrushSetOpacityDart>(
          'krita_brush_set_opacity');
  late final _KritaBrushSetSpacingDart _setSpacing = _lib
      .lookupFunction<_KritaBrushSetSpacingNative, _KritaBrushSetSpacingDart>(
          'krita_brush_set_spacing');
  late final _KritaBrushSetSmudgeDart _setSmudge = _lib
      .lookupFunction<_KritaBrushSetSmudgeNative, _KritaBrushSetSmudgeDart>(
          'krita_brush_set_smudge');
  late final _KritaBrushSetFlowDart _setFlow = _lib
      .lookupFunction<_KritaBrushSetFlowNative, _KritaBrushSetFlowDart>(
          'krita_brush_set_flow');
  late final _KritaBrushSetHardnessDart _setHardness = _lib
      .lookupFunction<_KritaBrushSetHardnessNative, _KritaBrushSetHardnessDart>(
          'krita_brush_set_hardness');
  late final _KritaBrushGenerateDabDart _generateDab = _lib.lookupFunction<
      _KritaBrushGenerateDabNative,
      _KritaBrushGenerateDabDart>('krita_brush_generate_dab');
  late final _KritaBrushReleaseDabDart _releaseDab = _lib
      .lookupFunction<_KritaBrushReleaseDabNative, _KritaBrushReleaseDabDart>(
          'krita_brush_release_dab');
  late final _KritaBrushCleanupDart _cleanup = _lib
      .lookupFunction<_KritaBrushCleanupNative, _KritaBrushCleanupDart>(
          'krita_brush_cleanup');
  late final _KritaBrushLastErrorDart _lastError = _lib
      .lookupFunction<_KritaBrushLastErrorNative, _KritaBrushLastErrorDart>(
          'krita_brush_last_error');

  /// Loads a Krita brush preset (.kpp) from the filesystem.
  ///
  /// Returns `true` on success. On failure [lastError] will contain a
  /// description. After a successful load, read [currentSize],
  /// [currentOpacity] and [currentSpacing] to reflect the preset's values
  /// in the app UI.
  bool loadPreset(String path) {
    _checkAlive();
    final pathPtr = path.toNativeUtf8();
    try {
      final r = _loadPreset(_handle, pathPtr);
      return r == 0;
    } finally {
      calloc.free(pathPtr);
    }
  }

  // ----- Parameter getters (reflect loaded presets into the UI) ----------

  late final _KritaBrushGetSizeDart _getSize =
      _lib.lookupFunction<_KritaBrushGetSizeNative, _KritaBrushGetSizeDart>(
          'krita_brush_get_size');
  late final _KritaBrushGetOpacityDart _getOpacity =
      _lib.lookupFunction<_KritaBrushGetOpacityNative, _KritaBrushGetOpacityDart>(
          'krita_brush_get_opacity');
  late final _KritaBrushGetSpacingDart _getSpacing =
      _lib.lookupFunction<_KritaBrushGetSpacingNative, _KritaBrushGetSpacingDart>(
          'krita_brush_get_spacing');
  late final _KritaBrushGetHardnessDart _getHardness =
      _lib.lookupFunction<_KritaBrushGetHardnessNative, _KritaBrushGetHardnessDart>(
          'krita_brush_get_hardness');
  late final _KritaBrushGetFlowDart _getFlow =
      _lib.lookupFunction<_KritaBrushGetFlowNative, _KritaBrushGetFlowDart>(
          'krita_brush_get_flow');
  late final _KritaBrushGetEraserDart _getEraser =
      _lib.lookupFunction<_KritaBrushGetEraserNative, _KritaBrushGetEraserDart>(
          'krita_brush_get_eraser');
  late final _KritaBrushGetPresetNameDart _getPresetName =
      _lib.lookupFunction<_KritaBrushGetPresetNameNative, _KritaBrushGetPresetNameDart>(
          'krita_brush_get_preset_name');

  /// The brush diameter currently set on the native engine.
  double get currentSize {
    _checkAlive();
    return _getSize(_handle);
  }

  /// The flow / opacity currently set on the native engine.
  double get currentOpacity {
    _checkAlive();
    return _getOpacity(_handle);
  }

  /// The dab spacing currently set on the native engine.
  double get currentSpacing {
    _checkAlive();
    return _getSpacing(_handle);
  }

  /// The hardness currently set on the native engine.
  double get currentHardness {
    _checkAlive();
    return _getHardness(_handle);
  }

  /// The flow (per-dab application rate) currently set on the native
  /// engine, in [0, 1] (default 1.0). Reflects either a [flow] setter
  /// call or a preset's FlowValue sensor base. Flow < 1 scales each
  /// dab's alpha so paint builds up gradually over multiple stamps.
  double get currentFlow {
    _checkAlive();
    return _getFlow(_handle);
  }

  /// Whether the loaded preset is an eraser preset (settings-level
  /// Krita/erase, EraserMode or CompositeOp=erase). Stroke compositing
  /// should switch to destination-out while this is true.
  bool get isEraserPreset {
    _checkAlive();
    return _getEraser(_handle);
  }

  /// The name of the last successfully loaded preset, or '' if none.
  String get currentPresetName {
    _checkAlive();
    final ptr = _getPresetName(_handle);
    if (ptr == nullptr) return '';
    return ptr.toDartString();
  }

  /// Sets the brush diameter in pixels.
  set size(double pixels) {
    _checkAlive();
    _setSize(_handle, pixels);
  }

  /// Sets the brush color.
  set color(BrushColor c) {
    _checkAlive();
    _setColor(_handle, c.packed);
  }

  /// Sets the brush flow / opacity in range [0, 1].
  set opacity(double value) {
    _checkAlive();
    _setOpacity(_handle, value.clamp(0.0, 1.0));
  }

  /// Sets the dab spacing (fraction of brush diameter) in range [0, 5].
  set spacing(double value) {
    _checkAlive();
    _setSpacing(_handle, value.clamp(0.0, 5.0));
  }

  /// Sets the smudge ratio in range [0, 1] (0 == no smudge, 1 == pure smudge).
  set smudge(double value) {
    _checkAlive();
    _setSmudge(_handle, value.clamp(0.0, 1.0));
  }

  /// Sets the brush flow (per-dab application rate) in range [0, 1].
  /// Flow < 1 scales each dab's alpha so paint builds up gradually over
  /// multiple stamps. Distinct from [opacity] (the master multiplier
  /// applied by the host compositor).
  set flow(double value) {
    _checkAlive();
    _setFlow(_handle, value.clamp(0.0, 1.0));
  }

  /// Sets the brush hardness in range [0, 1] (0 = fully soft gaussian
  /// falloff, 1 = hard-edged disk). On the real engine this rebuilds
  /// the mask generator's fade.
  set hardness(double value) {
    _checkAlive();
    _setHardness(_handle, value.clamp(0.0, 1.0));
  }

  /// Generates a single dab image for the given input.
  ///
  /// The returned [BrushDab] owns a copy of the pixel data, so callers may
  /// hold onto it indefinitely. Returns an empty dab if the engine rejects
  /// the input (e.g. zero pressure and skip-on-zero enabled).
  BrushDab generateDab(BrushInput input) {
    _checkAlive();
    final inputPtr = calloc<BrushInputNative>();
    final dabPtr = calloc<BrushDabNative>();
    try {
      input._writeTo(inputPtr.ref);
      dabPtr.ref.width = 0;
      dabPtr.ref.height = 0;
      dabPtr.ref.stride = 0;
      dabPtr.ref.reserved = 0;
      dabPtr.ref.pixels = nullptr;

      final ok = _generateDab(_handle, inputPtr, dabPtr);
      if (!ok) {
        return BrushDab(width: 0, height: 0, stride: 0, pixels: Uint8List(0));
      }
      final w = dabPtr.ref.width;
      final h = dabPtr.ref.height;
      final stride = dabPtr.ref.stride == 0 ? w * 4 : dabPtr.ref.stride;
      final pixelsPtr = dabPtr.ref.pixels;
      if (w <= 0 || h <= 0 || pixelsPtr == nullptr) {
        return BrushDab(width: 0, height: 0, stride: 0, pixels: Uint8List(0));
      }
      final byteCount = stride * h;
      // Copy the native pixel buffer into a Dart-owned Uint8List so the
      // data remains valid after we release the native dab.
      final pixels = Uint8List.fromList(pixelsPtr.asTypedList(byteCount));

      // Release the native buffer now that we have our own copy.
      _releaseDab(_handle, dabPtr);
      dabPtr.ref.pixels = nullptr;

      return BrushDab(width: w, height: h, stride: stride, pixels: pixels);
    } finally {
      calloc.free(inputPtr);
      // If generate_dab failed the pointer may still be null but freeing it
      // is safe.
      if (dabPtr.ref.pixels != nullptr) {
        _releaseDab(_handle, dabPtr);
      }
      calloc.free(dabPtr);
    }
  }

  /// Resets the internal stroke state (called between strokes).
  void cleanup() {
    _checkAlive();
    _cleanup(_handle);
  }

  /// Returns the most recent error message produced by the engine, or an
  /// empty string if there is none.
  String lastError() {
    _checkAlive();
    final ptr = _lastError(_handle);
    if (ptr == nullptr) return '';
    final msg = ptr.toDartString();
    return msg;
  }

  /// Releases the native brush handle. After this the instance is unusable.
  void dispose() {
    if (_disposed) return;
    _disposed = true;
    _cleanup(_handle);
    _destroy(_handle);
  }

  void _checkAlive() {
    if (_disposed) {
      throw StateError('KritaBrushEngine has been disposed');
    }
  }
}
