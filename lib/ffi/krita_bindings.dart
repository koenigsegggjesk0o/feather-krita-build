/// Mirrors `BrushInput` in `krita_bridge.h`.
///
/// Describes the state of the stylus / pointer at one instant in time. The
/// layout is identical to the C struct: 6 doubles + 2 floats + 2 int32
/// (flags + explicit padding), total 64 bytes.
final class BrushInputNative extends Struct {
  /// X position in device-independent pixels relative to the dab origin.
  @Double()
  external double x;

  /// Y position in device-independent pixels relative to the dab origin.
  @Double()
  external double y;

  /// Normalized pressure in range [0, 1] (1.0 == max pressure).
  @Double()
  external double pressure;

  /// X tilt in degrees, range [-90, 90].
  @Double()
  external double tiltX;

  /// Y tilt in degrees, range [-90, 90].
  @Double()
  external double tiltY;

  /// Time in seconds since stroke start.
  @Double()
  external double time;

  /// Velocity along X axis (px/s).
  @Float()
  external double velocityX;

  /// Velocity along Y axis (px/s).
  @Float()
  external double velocityY;

  /// Bitfield of button/modifier flags (see [BrushInputFlags]).
  @Int32()
  external int flags;

  @Int32()
  // ignore: unused_field
  external int _padding;
}

/// Mirrors `BrushDab` in `krita_bridge.h`.
///
/// Represents a single stamp (dab) generated by Krita's brush engine. The
/// pixel buffer is allocated on the native side and owned by the bridge —
/// Dart must copy it out via [KritaBrushEngine._readDab] and then release
/// the buffer with `krita_brush_release_dab`.
final class BrushDabNative extends Struct {
  /// Width of the dab image in pixels.
  @Int32()
  external int width;

  /// Height of the dab image in pixels.
  @Int32()
  external int height;

  /// Number of bytes per pixel row (== width * 4 for RGBA8).
  @Int32()
  external int stride;

  /// Reserved for alignment / future use.
  @Int32()
  external int reserved;

  /// Pointer to width*height*4 bytes of RGBA8 pixel data (premultiplied).
  external Pointer<Uint8> pixels;
}

