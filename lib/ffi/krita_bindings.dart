/// Loads the `krita_bridge` native library for the current platform.
///
/// On Android the library is bundled inside the APK and Android loads it
/// automatically. On desktop platforms we resolve a system path.
DynamicLibrary _loadKritaBridge() {
  if (Platform.isAndroid || Platform.isIOS) {
    return DynamicLibrary.open('libkrita_bridge.so');
  }
  if (Platform.isWindows) {
    // Try a few candidate locations next to the executable.
    final candidates = <String>[
      'krita_bridge.dll',
      'lib\\krita_bridge.dll',
      '.\\krita_bridge.dll',
    ];
    for (final c in candidates) {
      try {
        return DynamicLibrary.open(c);
      } on ArgumentError {
        // continue
      }
    }
    throw StateError('krita_bridge.dll not found in search path');
  }
  if (Platform.isLinux) {
    // Try several candidate locations: alongside the executable, in the
    // bundle's lib folder, in a dev path, and finally the bare name (which
    // relies on LD_LIBRARY_PATH).
    final candidates = <String>[
      'lib/libkrita_bridge.so',
      'libkrita_bridge.so',
      './libkrita_bridge.so',
      'assets/native/linux/libkrita_bridge.so',
      'assets/native/libkrita_bridge.so',
      '../assets/native/linux/libkrita_bridge.so',
    ];
    for (final c in candidates) {
      try {
        return DynamicLibrary.open(c);
      } on ArgumentError {
        // continue
      } on OSError {
        // continue
      }
    }
    throw StateError('libkrita_bridge.so not found. Set LD_LIBRARY_PATH or '
        'place the .so next to the executable.');
  }
  if (Platform.isMacOS) {
    return DynamicLibrary.open('libkrita_bridge.dylib');
  }
  throw UnsupportedError('Krita bridge not supported on this platform');
}

