    return _getFlow(_handle);
  }

  /// The smudge rate currently set on the native engine, in [0, 1]
  /// (default 0.0). Mirrors [krita_brush_get_smudge], which the C ABI
  /// has always exported — the Dart getter just was not needed until the
  /// live param editor (5-loop-69) started re-syncing sliders from
  /// engine-side edits.
  double get currentSmudge {
    _checkAlive();
    return _getSmudge(_handle);
  }

  /// Whether the loaded preset is an eraser preset (settings-level
  /// Krita/erase, EraserMode or CompositeOp=erase). Stroke compositing
  /// should switch to destination-out while this is true.
  bool get isEraserPreset {
    _checkAlive();
    return _getEraser(_handle);
  }

  /// The name of the last successfully loaded preset, or '' if none.
  String get currentPresetName {
    _checkAlive();
    final ptr = _getPresetName(_handle);
    if (ptr == nullptr) return '';
    return ptr.toDartString();
  }

  /// The loaded preset's declared paintop family (root
  /// `<Preset paintopid="...">` / `<Paintop id="...">` attribute —
  /// "paintbrush", "eraser", "spray", ...), or '' when no preset is
  /// loaded or the preset omits the attribute. Lets the UI show which
  /// family a preset belongs to and gate per-paintop options (e.g.
  /// Krita only offers hardness to auto-brush paintops).
  String get currentPaintopId {
    _checkAlive();
    final ptr = _getPaintopId(_handle);
    if (ptr == nullptr) return '';
    return ptr.toDartString();
  }

  /// The number of paintop-settings-level parameters captured from the
  /// last successfully loaded preset (0 before the first load, after a
  /// failed load, or on the fallback bridge). See [presetParams].
  int get presetParamCount {
    _checkAlive();
    return _presetParamCount(_handle);
  }

  /// The parameter NAME at [index] (document order) from the last
  /// successfully loaded preset, or null when out of range.
  String? presetParamNameAt(int index) {
    _checkAlive();
    final ptr = _presetParamNameAt(_handle, index);
    if (ptr == nullptr) return null;
    return ptr.toDartString();
  }

  /// The parameter VALUE at [index] (document order) from the last
  /// successfully loaded preset, or null when out of range. Values are
  /// raw settings strings (e.g. "100" for Krita/opacity, "erase" for
  /// CompositeOp, full `<Brush ...>` XML for brush_definition).
  String? presetParamValueAt(int index) {
    _checkAlive();
    final ptr = _presetParamValueAt(_handle, index);
    if (ptr == nullptr) return null;
    return ptr.toDartString();
  }

  /// The loaded preset's paintop-settings-level parameters (roadmap (f))
  /// as an insertion-ordered name -> value map: every `<param>` entry in
  /// the preset XML, exactly as Krita's paintop settings wrote it
  /// (Krita/opacity, CompositeOp, FlowValue, OpacityValue, ...). The UI
  /// can render genuine per-preset option surfaces from this without
  /// hard-coding parameter names. Empty on the fallback bridge and
  /// before the first successful [loadPreset].
  Map<String, String> presetParams() {
    _checkAlive();
    final n = _presetParamCount(_handle);
    if (n <= 0) return const <String, String>{};
    return Map<String, String>.fromEntries(List.generate(n, (i) {
      final namePtr = _presetParamNameAt(_handle, i);
      final valuePtr = _presetParamValueAt(_handle, i);
      return MapEntry(
        namePtr == nullptr ? '' : namePtr.toDartString(),
        valuePtr == nullptr ? '' : valuePtr.toDartString(),
      );
    }));
  }

  /// Sets a paintop-settings-level parameter of the loaded preset by
  /// NAME (roadmap (f) live param editing, 5-loop-69). The real bridge
  /// records the (name, value) pair in its param map of record (visible
  /// through [presetParams]) and applies the live effect for consumed
  /// keys — Krita/opacity (0-100), OpacityValue/opacity/brush_opacity
  /// (0-1), FlowValue/flow (0-1), hardness (0-1, rebuilds the tip),
  /// SoftnessValue/softness (0-1 complement, rebuilds the tip),
  /// brush_spacing (0-5], SmudgeRateValue/smudge_rate/smudge (0-1),
  /// Krita/erase / EraserMode / eraser ("true"/"1") and CompositeOp
  /// ("erase"). Unknown names are recorded and return true — the
  /// wrapper's dab model simply has no dimension for them.
  ///
  /// Returns false when the bridge rejects the edit (no preset loaded,
  /// empty name) OR when the loaded engine artifact predates the
  /// export: the symbol lookup throws [ArgumentError] on such builds
  /// (staged engines from before this ABI addition, e.g. the v0.45
  /// release), which this method catches and reports as "not
  /// supported". Throws [ArgumentError] for an empty [name] argument
  /// before touching the engine.
  bool setParam(String name, String value) {
    if (name.trim().isEmpty) {
      throw ArgumentError.value(name, 'name', 'must not be empty');
    }
    _checkAlive();
    final namePtr = name.toNativeUtf8();
    final valuePtr = value.toNativeUtf8();
    try {
      return _setParam(_handle, namePtr, valuePtr) != 0;
    } on ArgumentError {
      // Engine artifact predates krita_brush_set_param — live param
      // editing is not available on this build.
      return false;
    } finally {
      calloc.free(namePtr);
      calloc.free(valuePtr);
    }
  }

  /// Reads the raw sensor-curve XML recorded on the loaded preset's
  /// param map for [key] (milestone (i) curve editing, 5-loop-76).
  /// Curve keys are the paintop-settings entries named
  /// "<CurveOption>Sensor" ("FlowSensor", "SizeSensor", ...) whose
  /// values are dynamic-sensor params XML — `<!DOCTYPE params>
  /// <params id="pressure"> <curve>0,0;1,1;</curve> </params>` —
  /// semicolon-separated x,y point pairs in [0,1]^2. Some sensors ship
  /// the EMPTY form `<params id="pressure"/>` (no <curve> child): the
  /// raw string is still returned, callers must handle the missing
  /// curve element themselves (the curve editor seeds a linear default
  /// in that case).
  ///
  /// Returns null when the key is absent from the map, the arguments
  /// are bad, no preset is loaded, the loaded bridge is a
  /// portable/fallback build (returns NULL unconditionally — the
  /// capability probe), or the loaded engine artifact predates the
  /// get_curve export (symbol lookup throws [ArgumentError]).
  String? getCurve(String key) {
    if (key.trim().isEmpty) return null;
    _checkAlive();
    try {
      final keyPtr = key.toNativeUtf8();
      try {
        final ptr = _getCurve(_handle, keyPtr);
        if (ptr == nullptr) return null;
        return ptr.toDartString();
      } finally {
        calloc.free(keyPtr);
      }
    } on ArgumentError {
      // Engine artifact predates krita_brush_get_curve — curve
      // reading is not available on this build.
      return null;
    }
  }

  /// Records a validated sensor-curve XML for [key] on the loaded
  /// preset's param map (replace-or-append, same policy as [setParam];
  /// milestone (i) curve editing). [curveXml] must be the engine's own
  /// KisDynamicSensorData shape — root <params> with a non-empty id
  /// attribute and exactly one <curve> child holding >= 2 semicolon
  /// separated "x,y;" float pairs, both axes finite in [0,1]. Curves
  /// are recorded engine-side and applied host-side (no live dab-model
  /// effect is claimed for them).
  ///
  /// Returns [CurveEditStatus.recorded] on success,
  /// [CurveEditStatus.rejected] when the engine rejects the payload or
  /// has no preset loaded, and [CurveEditStatus.unsupported] on
  /// portable/fallback bridges (always 0) or engine artifacts that
  /// predate the set_curve export (symbol lookup throws
  /// [ArgumentError]). Throws [ArgumentError] for empty Dart-side
  /// arguments before touching the engine.
  CurveEditStatus setCurve(String key, String curveXml) {
    if (key.trim().isEmpty) {
      throw ArgumentError.value(key, 'key', 'must not be empty');
    }
    if (curveXml.trim().isEmpty) {
      throw ArgumentError.value(curveXml, 'curveXml', 'must not be empty');
    }
    _checkAlive();
    final keyPtr = key.toNativeUtf8();
    final xmlPtr = curveXml.toNativeUtf8();
    try {
      final rc = _setCurve(_handle, keyPtr, xmlPtr);
      if (rc == 1) return CurveEditStatus.recorded;
      if (rc == -1) return CurveEditStatus.rejected;
      return CurveEditStatus.unsupported;
    } on ArgumentError {
      // Engine artifact predates krita_brush_set_curve — curve
      // editing is not available on this build.
      return CurveEditStatus.unsupported;
    } finally {
      calloc.free(keyPtr);
      calloc.free(xmlPtr);
    }
  }

  /// The loaded bridge's self-identification string, verbatim from
  /// krita_brush_version — e.g. "FeatherBridge-Krita/2.0 (real engine
  /// 5.3.4)" on the real bridge (the runtime version inside the
  /// parens is the engine's own self-report; the upstream v6.0.4
  /// sources' Qt5 build configuration reports 5.3.x), or the
  /// portable/fallback builds' own honest labels. The C pointer is
  /// static for the library's lifetime (krita_bridge.h), so the
  /// returned Dart string is stable across calls.
  ///
  /// Returns null when the loaded engine artifact predates the export
  /// (symbol lookup throws [ArgumentError]) or the bridge reports a
  /// null/empty string.
  String? engineVersion() {
    _checkAlive();
    try {
      final ptr = _version();
      if (ptr == nullptr) return null;
      final s = ptr.toDartString();
      return s.isEmpty ? null : s;
    } on ArgumentError {
      // Engine artifact predates krita_brush_version — the badge
      // collapses to nothing on this build.
      return null;
    }
  }

  /// Sets the brush diameter in pixels.
  set size(double pixels) {
    _checkAlive();
    _setSize(_handle, pixels);
  }

  /// Scans [dir] recursively for .kpp presets through the REAL engine's
  /// own container parser (ZIP KoStore / legacy PNG zTXt / bare XML) and
  /// memoizes name + paintop family per preset on the native handle.
  /// Returns the number of presets found, or a negative code on bad
  /// arguments / missing directory (see krita_bridge.h). The parsed
  /// entries are read back with [scannedPresets].
  /// Throws [ArgumentError] on null/empty [dir].
  int scanPresetFamilies(String dir) {
    if (dir.isEmpty) throw ArgumentError.value(dir, 'dir', 'must not be empty');
    _checkAlive();
    final dirPtr = dir.toNativeUtf8();
    try {
      return _presetScan(_handle, dirPtr);
    } finally {
      calloc.free(dirPtr);
    }
  }

  /// The preset entries recorded by the last [scanPresetFamilies] call,
  /// in scan order (sorted by path). Each entry carries the engine-parsed
  /// display name and declared paintop family plus the absolute file
  /// path (feed it to [loadPreset]).
  List<KritaPresetInfo> scannedPresets() {
    _checkAlive();
    final n = _presetCount(_handle);
    if (n <= 0) return const <KritaPresetInfo>[];
    return List<KritaPresetInfo>.generate(n, (i) {
      String read(Pointer<Utf8> Function(Pointer<Void>, int) fn) {
        final ptr = fn(_handle, i);
        return ptr == nullptr ? '' : ptr.toDartString();
      }
      return KritaPresetInfo(
        name: read(_presetNameAt),
        family: read(_presetFamilyAt),
        path: read(_presetPathAt),
      );
    });
  }

  /// Sets the brush color.
  set color(BrushColor c) {
    _checkAlive();
    _setColor(_handle, c.packed);
  }

  /// Sets the brush flow / opacity in range [0, 1].
  set opacity(double value) {
    _checkAlive();
    _setOpacity(_handle, value.clamp(0.0, 1.0));
  }

  /// Sets the dab spacing (fraction of brush diameter) in range [0, 5].
  set spacing(double value) {
    _checkAlive();
    _setSpacing(_handle, value.clamp(0.0, 5.0));
  }

  /// Sets the smudge ratio in range [0, 1] (0 == no smudge, 1 == pure smudge).
  set smudge(double value) {
    _checkAlive();
    _setSmudge(_handle, value.clamp(0.0, 1.0));
  }

  /// Sets the brush flow (per-dab application rate) in range [0, 1].
  /// Flow < 1 scales each dab's alpha so paint builds up gradually over
  /// multiple stamps. Distinct from [opacity] (the master multiplier
  /// applied by the host compositor).
  set flow(double value) {
    _checkAlive();
    _setFlow(_handle, value.clamp(0.0, 1.0));
  }

  /// Sets the brush hardness in range [0, 1] (0 = fully soft gaussian
  /// falloff, 1 = hard-edged disk). On the real engine this rebuilds
  /// the mask generator's fade.
  set hardness(double value) {
    _checkAlive();
    _setHardness(_handle, value.clamp(0.0, 1.0));
  }

  /// Generates a single dab image for the given input.
  ///
  /// The returned [BrushDab] owns a copy of the pixel data, so callers may
  /// hold onto it indefinitely. Returns an empty dab if the engine rejects
  /// the input (e.g. zero pressure and skip-on-zero enabled).
  BrushDab generateDab(BrushInput input) {
    _checkAlive();
    final inputPtr = calloc<BrushInputNative>();
    final dabPtr = calloc<BrushDabNative>();
    try {
      input._writeTo(inputPtr.ref);
      dabPtr.ref.width = 0;
      dabPtr.ref.height = 0;
      dabPtr.ref.stride = 0;
      dabPtr.ref.reserved = 0;
      dabPtr.ref.pixels = nullptr;

      final ok = _generateDab(_handle, inputPtr, dabPtr);
      if (!ok) {
        return BrushDab(width: 0, height: 0, stride: 0, pixels: Uint8List(0));
      }
      final w = dabPtr.ref.width;
      final h = dabPtr.ref.height;
      final stride = dabPtr.ref.stride == 0 ? w * 4 : dabPtr.ref.stride;
      final pixelsPtr = dabPtr.ref.pixels;
      if (w <= 0 || h <= 0 || pixelsPtr == nullptr) {
        return BrushDab(width: 0, height: 0, stride: 0, pixels: Uint8List(0));
      }
      final byteCount = stride * h;
      // Copy the native pixel buffer into a Dart-owned Uint8List so the
      // data remains valid after we release the native dab.
      final pixels = Uint8List.fromList(pixelsPtr.asTypedList(byteCount));

      // Release the native buffer now that we have our own copy.
      _releaseDab(_handle, dabPtr);
      dabPtr.ref.pixels = nullptr;

      return BrushDab(width: w, height: h, stride: stride, pixels: pixels);
    } finally {
      calloc.free(inputPtr);
      // If generate_dab failed the pointer may still be null but freeing it
      // is safe.
      if (dabPtr.ref.pixels != nullptr) {
        _releaseDab(_handle, dabPtr);
      }
      calloc.free(dabPtr);
    }
  }

  /// Resets the internal stroke state (called between strokes).
  void cleanup() {
    _checkAlive();
    _cleanup(_handle);
  }

  /// Returns the most recent error message produced by the engine, or an
  /// empty string if there is none.
  String lastError() {
    _checkAlive();
    final ptr = _lastError(_handle);
    if (ptr == nullptr) return '';
    final msg = ptr.toDartString();
    return msg;
  }

  /// Releases the native brush handle. After this the instance is unusable.
  void dispose() {
    if (_disposed) return;
    _disposed = true;
    _cleanup(_handle);
    _destroy(_handle);
  }

  void _checkAlive() {
    if (_disposed) {
      throw StateError('KritaBrushEngine has been disposed');
    }
  }
}

/// One preset entry from an engine-side directory scan
/// ([KritaBrushEngine.scanPresetFamilies]).
class KritaPresetInfo {
  const KritaPresetInfo({
    required this.name,
    required this.family,
    required this.path,
  });

  /// Engine-parsed display name (root `name` attribute, else file name).
  final String name;

  /// Declared paintop family (root `paintopid` / `<Paintop id>`), '' when
  /// the preset omits it.
  final String family;

  /// Absolute file path (loadable through [KritaBrushEngine.loadPreset]).
  final String path;

  @override
  String toString() => 'KritaPresetInfo($name, family=$family)';
}
