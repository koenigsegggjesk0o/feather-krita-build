// krita_bindings.dart — Dart FFI bindings to Krita C++ brush engine
//
// Bridges Flutter/Dart to the native `krita_bridge` shared library which
// calls Krita's public brush API (KisBrush, KisPaintOp, etc.).
//
// The high-level [KritaBrushEngine] wraps the raw FFI calls into a clean
// Dart-friendly API used by the engine layer.

